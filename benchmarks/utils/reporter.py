from datetime import datetime, timezone
from pathlib import Path
from typing import Mapping

from benchmarks.utils.metrics import (
    ClassificationMetrics,
    LatencyMetrics,
)
from benchmarks.utils.models import BenchmarkRecord


class MarkdownBenchmarkReporter:
    def __init__(
        self,
        output_path: str | Path,
        title: str,
    ) -> None:
        self._path = Path(output_path)
        self._title = title

    def write(
        self,
        records: list[BenchmarkRecord],
        latency: LatencyMetrics,
        classification: (
            ClassificationMetrics | None
        ) = None,
        environment: (
            Mapping[str, str] | None
        ) = None,
    ) -> None:
        self._path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        if not self._path.exists():
            self._write_header()

        timestamp = datetime.now(
            timezone.utc
        ).isoformat()

        with self._path.open(
            "a",
            encoding="utf-8",
        ) as file:
            file.write(
                f"\n## Run — {timestamp}\n\n"
            )

            if environment:
                self._write_environment(
                    file,
                    environment,
                )

            if classification:
                self._write_classification(
                    file,
                    classification,
                )

            self._write_latency(
                file,
                latency,
            )

            self._write_records(
                file,
                records,
            )

            self._write_failures(
                file,
                records,
            )

    def _write_header(self) -> None:
        self._path.write_text(
            f"# {self._title}\n\n"
            "This file is generated by the GuardFlow "
            "benchmark suite.\n\n"
            "Results are committed to Git so accuracy, "
            "false positives and latency can be tracked "
            "across implementation and model changes.\n",
            encoding="utf-8",
        )

    @staticmethod
    def _write_environment(
        file,
        environment: Mapping[str, str],
    ) -> None:
        file.write(
            "### Environment\n\n"
        )

        for key, value in environment.items():
            file.write(
                f"- **{key}:** {value}\n"
            )

        file.write("\n")

    @staticmethod
    def _write_classification(
        file,
        metrics: ClassificationMetrics,
    ) -> None:
        file.write(
            "### Classification Metrics\n\n"
        )

        file.write(
            "| Metric | Value |\n"
            "|---|---:|\n"
            f"| Total | {metrics.total} |\n"
            f"| True positives | "
            f"{metrics.true_positive} |\n"
            f"| True negatives | "
            f"{metrics.true_negative} |\n"
            f"| False positives | "
            f"{metrics.false_positive} |\n"
            f"| False negatives | "
            f"{metrics.false_negative} |\n"
            f"| Accuracy | "
            f"{metrics.accuracy:.4f} |\n"
            f"| Precision | "
            f"{metrics.precision:.4f} |\n"
            f"| Recall | "
            f"{metrics.recall:.4f} |\n"
            f"| F1 | "
            f"{metrics.f1:.4f} |\n"
            f"| False-positive rate | "
            f"{metrics.false_positive_rate:.4f} |\n\n"
        )

    @staticmethod
    def _write_latency(
        file,
        metrics: LatencyMetrics,
    ) -> None:
        file.write(
            "### Latency\n\n"
        )

        file.write(
            "| Metric | ms |\n"
            "|---|---:|\n"
            f"| Minimum | "
            f"{metrics.minimum_ms:.2f} |\n"
            f"| Average | "
            f"{metrics.average_ms:.2f} |\n"
            f"| P50 | "
            f"{metrics.p50_ms:.2f} |\n"
            f"| P95 | "
            f"{metrics.p95_ms:.2f} |\n"
            f"| Maximum | "
            f"{metrics.maximum_ms:.2f} |\n\n"
        )

    @staticmethod
    def _write_records(
        file,
        records: list[BenchmarkRecord],
    ) -> None:
        file.write(
            "### Cases\n\n"
        )

        file.write(
            "| Case | Category | Expected | Actual | "
            "Score | Latency ms | Result | Input |\n"
        )

        file.write(
            "|---|---|---|---|---:|---:|---|---|\n"
        )

        for record in records:
            score = (
                f"{record.score:.4f}"
                if record.score is not None
                else "-"
            )

            result = (
                "PASS"
                if record.passed
                else "FAIL"
            )

            file.write(
                f"| {record.case_id} "
                f"| {record.category} "
                f"| {record.expected} "
                f"| {record.actual} "
                f"| {score} "
                f"| {record.latency_ms:.2f} "
                f"| {result} "
                f"| {_sanitize_markdown(record.input_text)} "
                f"|\n"
            )

        file.write("\n")

    @staticmethod
    def _write_failures(
        file,
        records: list[BenchmarkRecord],
    ) -> None:
        failures = [
            record
            for record in records
            if not record.passed
        ]

        if not failures:
            return

        file.write(
            "### Failed Cases\n\n"
        )

        for failure in failures:
            file.write(
                f"#### {failure.case_id}\n\n"
                f"- Category: "
                f"`{failure.category}`\n"
                f"- Expected: "
                f"`{failure.expected}`\n"
                f"- Actual: "
                f"`{failure.actual}`\n"
            )

            if failure.score is not None:
                file.write(
                    f"- Score: "
                    f"`{failure.score:.4f}`\n"
                )

            file.write(
                f"- Input: "
                f"`{_sanitize_markdown(failure.input_text)}`"
                f"\n\n"
            )


def _sanitize_markdown(
    value: str,
    maximum_length: int = 180,
) -> str:
    cleaned = (
        value
        .replace("|", "\\|")
        .replace("\n", " ")
        .replace("\r", " ")
    )

    if len(cleaned) > maximum_length:
        return (
            cleaned[:maximum_length]
            + "..."
        )

    return cleaned